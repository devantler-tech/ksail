package gonotices

import (
	"bytes"
	"encoding/json"
	"io"
	"os"
	"slices"
)

type targetReceipt struct {
	Target         string `json:"target"`
	NoticesSHA256  string `json:"noticesSha256"`
	ManifestSHA256 string `json:"manifestSha256"`
	Packages       int    `json:"packages"`
	Files          int    `json:"files"`
}

type generatedReceipt struct {
	Schema                 int               `json:"schema"`
	Inputs                 map[string]string `json:"inputs"`
	ToolchainVersion       string            `json:"toolchainVersion"`
	ToolchainLicenseSHA256 string            `json:"toolchainLicenseSha256"`
	Targets                []targetReceipt   `json:"targets"`
}

// WriteReceipt records the exact generated bytes of all eight source targets.
func WriteReceipt(root string, payloads map[string]Payload) (err error) {
	data, err := receiptBytes(payloads)
	if err != nil {
		return err
	}

	if !ordinaryDirectories(root, ".github") {
		return ErrIncomplete
	}

	directory, err := os.OpenRoot(root)
	if err != nil {
		return ErrIncomplete
	}

	defer func() {
		if directory.Close() != nil {
			err = ErrIncomplete
		}
	}()

	return writeRecipientFile(directory, ".github/go-notice-receipts.json", data)
}

// VerifyReceipt compares all eight independently generated target expectations.
func VerifyReceipt(root string, payloads map[string]Payload) error {
	expected, err := receiptBytes(payloads)
	if err != nil {
		return err
	}

	actual, err := readMaterial(root, ".github/go-notice-receipts.json")
	if err != nil || !bytes.Equal(actual, expected) {
		return ErrIncomplete
	}

	return nil
}

func receiptBytes(payloads map[string]Payload) ([]byte, error) {
	targets := make([]string, 0, len(payloads))
	for target := range payloads {
		targets = append(targets, target)
	}

	if ValidateTargets(targets) != nil {
		return nil, ErrIncomplete
	}

	slices.Sort(targets)

	receipt := generatedReceipt{Schema: 1}
	for _, target := range targets {
		err := receipt.addTarget(target, payloads[target])
		if err != nil {
			return nil, err
		}
	}

	// Apply the reader's entry rules before writing, so a receipt that staging
	// would refuse can be neither written nor accepted by VerifyReceipt.
	if !receipt.validEntries() {
		return nil, ErrIncomplete
	}

	data, err := json.MarshalIndent(receipt, "", "  ")
	if err != nil {
		return nil, ErrIncomplete
	}

	return append(data, '\n'), nil
}

func (receipt *generatedReceipt) addTarget(target string, payload Payload) error {
	metadata, err := validatePayload(target, payload)
	if err != nil || metadata.Toolchain == nil {
		return ErrIncomplete
	}

	if receipt.Inputs == nil {
		receipt.Inputs = metadata.Inputs
		receipt.ToolchainVersion = metadata.Toolchain.Version
		receipt.ToolchainLicenseSHA256 = metadata.Toolchain.LicenseSHA256
	}

	if !receipt.matchesMetadata(metadata) {
		return ErrIncomplete
	}

	receipt.Targets = append(receipt.Targets, receiptTarget(target, payload, metadata))

	return nil
}

func receiptTarget(target string, payload Payload, metadata manifest) targetReceipt {
	files := 0
	for _, pkg := range metadata.Components {
		files += len(pkg.Files)
	}

	return targetReceipt{
		target,
		digest(payload.Text),
		digest(payload.Manifest),
		len(metadata.Components),
		files,
	}
}

func (receipt *generatedReceipt) matchesMetadata(metadata manifest) bool {
	return metadata.Toolchain != nil && sameFact(receipt.Inputs, metadata.Inputs) &&
		receipt.ToolchainVersion == metadata.Toolchain.Version &&
		receipt.ToolchainLicenseSHA256 == metadata.Toolchain.LicenseSHA256
}

func matchReceipt(root, target string, payload Payload) error {
	receipt, err := readGeneratedReceipt(root)
	if err != nil {
		return err
	}

	metadata, err := validatePayload(target, payload)
	if err != nil || !receipt.matchesMetadata(metadata) {
		return ErrIncomplete
	}

	expected := receiptTarget(target, payload, metadata)
	for _, entry := range receipt.Targets {
		if entry.Target == target && sameFact(entry, expected) {
			return nil
		}
	}

	return ErrIncomplete
}

func readGeneratedReceipt(root string) (generatedReceipt, error) {
	data, err := readMaterial(root, ".github/go-notice-receipts.json")
	if err != nil {
		return generatedReceipt{}, ErrIncomplete
	}

	decoder := json.NewDecoder(bytes.NewReader(data))
	decoder.DisallowUnknownFields()

	var receipt generatedReceipt
	if decoder.Decode(&receipt) != nil || decoder.Decode(new(any)) != io.EOF ||
		receipt.Schema != 1 {
		return generatedReceipt{}, ErrIncomplete
	}

	canonical, err := json.MarshalIndent(receipt, "", "  ")
	if err != nil || !bytes.Equal(append(canonical, '\n'), data) || !receipt.validEntries() {
		return generatedReceipt{}, ErrIncomplete
	}

	return receipt, nil
}

func (receipt *generatedReceipt) validEntries() bool {
	if !validSourceInputHashes(receipt.Inputs) || receipt.ToolchainVersion == "" ||
		!sha256Hex(receipt.ToolchainLicenseSHA256) {
		return false
	}

	names := make([]string, 0, len(receipt.Targets))

	previous := ""
	for _, entry := range receipt.Targets {
		if !entry.valid() || entry.Target <= previous {
			return false
		}

		previous = entry.Target
		names = append(names, entry.Target)
	}

	return ValidateTargets(names) == nil
}

func (entry targetReceipt) valid() bool {
	return sha256Hex(entry.NoticesSHA256) && sha256Hex(entry.ManifestSHA256) &&
		entry.Packages > 0 &&
		entry.Files > 0
}
